"""质量评估层：用人工标注集量化检索与问答的实际效果。

为什么单独一层
--------------
前面几个阶段都在回答「功能是否可用」，这一层回答「效果到底怎么样」——
而且是**可复现、可核对**地回答：

1. **标注集是人工写的**（``data/eval/*.json``），不是从检索结果反推出来的；
   每条标注都写明相关实体与相关性等级，并注明依据。
2. **指标是纯函数**（:mod:`src.eval.metrics`），公式写在文档字符串里，可以手算核对；
   不引入任何评估库，避免「指标怎么来的」变成黑盒。
3. **默认离线运行**：检索评估只依赖本地索引，回答评估默认走本地检索式后端，
   因此 ``pytest`` 与页面上的评估结果都能离线复现（不消耗任何 API 额度）。
   需要看真实大模型表现时用 ``--live`` 显式开启，并在报告中标明后端。

模块划分
--------

- :mod:`src.eval.metrics` —— 指标计算（Recall@K / Precision@K / Hit@K / MRR / AP / nDCG@K
  与引用覆盖、要点命中、拒答正确率）。
- :mod:`src.eval.dataset` —— 标注集的数据模型、加载与严格校验。
- :mod:`src.eval.runner` —— 把检索器 / 问答引擎跑在标注集上，产出结构化报告。
"""

